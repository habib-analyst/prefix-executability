"""Scripted agents.

Three policies, all deterministic and rule-based (no LLM anywhere):

* Baseline (reactive, validate-before-act): greedy FIRST-choice policy with
  no lookahead and no backtracking. It validates every proposed call
  against live state before emitting it, so its trajectories are (by
  construction) almost always fully executable — but it commits to first
  options, so it fails coordination tasks: round-trips on mismatched
  airlines, bundles across warehouses, modify-to-the-flight-it-holds.
  On an invalid proposal it stops (give-up), keeping TER high.

* Plan-conditioned (unverified): a globally coordinated plan generated by
  dry-running the correct policy on a snapshot of the world (so planned
  ids are concrete), then defect-injected with seeded probabilities:
  stale reference (nonexistent id), skipped precondition step (confirm /
  pay dropped), wrong argument type (int -> str). Executed blindly:
  invalid calls are no-ops and later calls keep their planned args.

* Dual-Loop (plan + pre-execution checking): the same defective plan,
  but every call is validated against live state BEFORE execution.
  - check-drop ablation: invalid calls are dropped, nothing else.
  - check-repair (the intervention): invalid calls are repaired —
    schema coercion, re-search + substitution for stale refs,
    prerequisite insertion for skipped steps, warehouse/fare/total
    correction — and dropped only if repair fails.

The divergence between the arms is emergent from these rules, not
hard-coded: no arm's success or TER is set directly anywhere.
"""

from __future__ import annotations

import copy
import random

from .tools import SCHEMAS, execute, validate
from .world import PASSENGER


def _call(tool, **args):
    return {"tool": tool, "args": args}


def _flights(world, origin, dest, date):
    return [fid for fid, f in sorted(world.flights.items())
            if f["origin"] == origin and f["dest"] == dest and f["date"] == date]


def _products(world, query):
    return [pid for pid, p in sorted(world.products.items())
            if p["category"] == query]


def _step(world, traj, call):
    """Validate-then-execute; append iff valid. Returns (ok, output)."""
    ok, out, _err = execute(world, call["tool"], call["args"])
    if ok:
        traj.append(call)
    return ok, out


def run_policy(task, world, coordinated):
    """Simulate a policy on a world copy; return the emitted trajectory.

    coordinated=True picks goal-consistent options (same airline for the
    return leg, same warehouse for the second bundle item, a different
    flight for modify). coordinated=False takes the first candidate.
    Either way a proposed call that fails validation stops the rollout
    (give-up), so emitted trajectories contain only valid calls.
    """
    w = world.fork()
    traj = []
    fam = task["family"]

    def flights(o, d, dt):
        cands = [f for f in _flights(w, o, d, dt) if w.flights[f]["seats"] > 0]
        return cands

    if fam == "oneway":
        _step(w, traj, _call("search_flights", origin=task["origin"],
                            dest=task["dest"], date=task["date"]))
        fl = flights(task["origin"], task["dest"], task["date"])
        if not fl:
            return traj
        _step(w, traj, _call("get_flight", flight_id=fl[0]))
        ok, out = _step(w, traj, _call("create_booking", flight_id=fl[0],
                                       passenger=task["passenger"]))
        if not ok:
            return traj
        bid = out["booking_id"]
        _step(w, traj, _call("confirm_booking", booking_id=bid))
        fare = w.flights[fl[0]]["fare"]
        _step(w, traj, _call("pay_booking", booking_id=bid, amount=fare))
        _step(w, traj, _call("send_notification", ref_id=bid, channel="email"))
        return traj

    if fam == "roundtrip":
        _step(w, traj, _call("search_flights", origin=task["origin"],
                            dest=task["dest"], date=task["date"]))
        outs = flights(task["origin"], task["dest"], task["date"])
        rets = flights(task["dest"], task["origin"], task["ret_date"])
        if not outs or not rets:
            return traj
        if coordinated:
            pair = next(((o, r) for o in outs for r in rets
                         if w.flights[o]["airline"] == w.flights[r]["airline"]), None)
            if pair is None:
                return traj
            o, r = pair
        else:
            o, r = outs[0], rets[0]
        for fid in (o, r):
            _step(w, traj, _call("get_flight", flight_id=fid))
            ok, out = _step(w, traj, _call("create_booking", flight_id=fid,
                                           passenger=task["passenger"]))
            if not ok:
                return traj
            bid = out["booking_id"]
            _step(w, traj, _call("confirm_booking", booking_id=bid))
            fare = w.flights[fid]["fare"]
            _step(w, traj, _call("pay_booking", booking_id=bid, amount=fare))
            _step(w, traj, _call("send_notification", ref_id=bid, channel="email"))
        return traj

    if fam in ("single", "bundle"):
        _step(w, traj, _call("search_products", query=task["query"]))
        cands = [p for p in _products(w, task["query"])
                 if w.products[p]["stock"] >= task["qty"]]
        if not cands:
            return traj
        p1 = cands[0]
        _step(w, traj, _call("get_product", product_id=p1))
        ok, out = _step(w, traj, _call("create_order", product_id=p1,
                                       qty=task["qty"]))
        if not ok:
            return traj
        oid = out["order_id"]
        if fam == "bundle":
            _step(w, traj, _call("search_products", query=task["query2"]))
            cands2 = [p for p in _products(w, task["query2"])
                      if w.products[p]["stock"] >= task["qty2"]]
            if coordinated:
                cands2 = [p for p in cands2
                          if w.products[p]["warehouse"] == w.orders[oid]["warehouse"]]
            if not cands2:
                return traj
            ok, _ = _step(w, traj, _call("add_item", order_id=oid,
                                         product_id=cands2[0], qty=task["qty2"]))
            if not ok:
                return traj
        total = w.orders[oid]["total"]
        _step(w, traj, _call("pay_order", order_id=oid, amount=total))
        _step(w, traj, _call("ship_order", order_id=oid))
        _step(w, traj, _call("send_notification", ref_id=oid, channel="email"))
        return traj

    if fam == "modify":
        _step(w, traj, _call("search_flights", origin=task["origin"],
                            dest=task["dest"], date=task["date"]))
        fl = flights(task["origin"], task["dest"], task["date"])
        if not fl:
            return traj
        ok, out = _step(w, traj, _call("create_booking", flight_id=fl[0],
                                       passenger=task["passenger"]))
        if not ok:
            return traj
        bid = out["booking_id"]
        _step(w, traj, _call("confirm_booking", booking_id=bid))
        _step(w, traj, _call("search_flights", origin=task["origin"],
                            dest=task["dest"], date=task["date"]))
        if coordinated:
            targets = [f for f in flights(task["origin"], task["dest"], task["date"])
                       if f != fl[0]]
        else:
            targets = _flights(w, task["origin"], task["dest"], task["date"])
        if not targets:
            return traj
        ok, _ = _step(w, traj, _call("modify_booking", booking_id=bid,
                                     new_flight_id=targets[0]))
        if not ok:
            return traj
        fare = w.flights[targets[0]]["fare"]
        _step(w, traj, _call("pay_booking", booking_id=bid, amount=fare))
        _step(w, traj, _call("send_notification", ref_id=bid, channel="email"))
        return traj

    return traj


# ---------------------------------------------------------------- defects

def _ref_args(call):
    return [a for a in call["args"]
            if a in ("flight_id", "new_flight_id", "booking_id",
                     "order_id", "product_id", "ref_id")]


def inject_defects(traj, rng, p_stale, p_skip, p_type):
    """Inject at most one defect of each class, each with its probability.

    stale: replace one referenced id with a nonexistent id of that kind.
    skip:  drop one droppable precondition step (confirm_booking/pay_order).
    type:  corrupt one int argument (qty/amount) to its string form.
    Returns (new_trajectory, [defect names applied]).
    """
    traj = copy.deepcopy(traj)
    applied = []
    if p_stale > 0 and rng.random() < p_stale:
        idxs = [i for i, c in enumerate(traj) if _ref_args(c)]
        if idxs:
            i = idxs[rng.randrange(len(idxs))]
            arg = _ref_args(traj[i])[0]
            prefix = {"flight_id": "FL", "new_flight_id": "FL",
                      "booking_id": "BK", "order_id": "OR",
                      "product_id": "PR", "ref_id": "BK"}[arg]
            traj[i]["args"][arg] = f"{prefix}-9999"
            applied.append("stale")
    if p_skip > 0 and rng.random() < p_skip:
        idxs = [i for i, c in enumerate(traj)
                if c["tool"] in ("confirm_booking", "pay_order")]
        if idxs:
            traj.pop(idxs[rng.randrange(len(idxs))])
            applied.append("skip")
    if p_type > 0 and rng.random() < p_type:
        idxs = [i for i, c in enumerate(traj)
                for a in ("qty", "amount") if a in c["args"]]
        if idxs:
            i = idxs[rng.randrange(len(idxs))]
            arg = "qty" if "qty" in traj[i]["args"] else "amount"
            traj[i]["args"][arg] = str(traj[i]["args"][arg])
            applied.append("type")
    return traj, applied


# ---------------------------------------------------------------- checker

def _bad_ref(world, call):
    """Return (arg_name, kind) of the first nonexistent reference, else None."""
    from .tools import _exists, REF_KIND
    for name, kind in REF_KIND.items():
        if name in call["args"] and not _exists(world, kind, call["args"][name]):
            return name, kind
    return None


def _latest(world, kind):
    ids = world.bookings if kind == "booking" else world.orders
    if not ids:
        return None
    return sorted(ids, key=lambda x: int(x.split("-")[1]))[-1]


def _exec(world, executed, call):
    ok, out, _ = execute(world, call["tool"], call["args"])
    if ok:
        executed.append(copy.deepcopy(call))
    return ok, out


def _repair(world, task, planned, executed, call, depth):
    """Try to execute `call` after repair. Returns True iff executed.

    Repair strategies, in error-kind order: schema coercion; re-search +
    substitution for stale refs; re-execution of the plan's create step
    for missing bookings/orders; prerequisite insertion / amount, fare,
    total, warehouse correction for precondition failures.
    """
    if depth > 3:
        return False
    ok, err = validate(world, call["tool"], call["args"])
    if ok:
        ok2, _ = _exec(world, executed, call)
        return ok2
    args = dict(call["args"])
    tool = call["tool"]

    if err == "schema":
        fixed = dict(args)
        for name, typ in SCHEMAS[tool].items():
            if name in fixed and typ is int and isinstance(fixed[name], str) \
                    and fixed[name].lstrip("-").isdigit():
                fixed[name] = int(fixed[name])
        if fixed != args:
            return _repair(world, task, planned, executed,
                           {"tool": tool, "args": fixed}, depth + 1)
        return False

    if err == "unknown_ref":
        bad = _bad_ref(world, call)
        if bad is None:
            return False
        arg, kind = bad
        if kind == "flight":
            search = _call("search_flights", origin=task["origin"],
                           dest=task["dest"], date=task["date"])
            _exec(world, executed, search)
            cands = [f for f in _flights(world, task["origin"], task["dest"], task["date"])
                     if world.flights[f]["seats"] > 0] or \
                _flights(world, task["origin"], task["dest"], task["date"])
            if not cands:
                return False
            args[arg] = cands[0]
            return _repair(world, task, planned, executed,
                           {"tool": tool, "args": args}, depth + 1)
        if kind == "product":
            query = task["query"] if tool == "create_order" else task.get("query2", task["query"])
            _exec(world, executed, _call("search_products", query=query))
            cands = [p for p in _products(world, query)
                     if world.products[p]["stock"] >= args.get("qty", 1)]
            if not cands:
                return False
            args[arg] = cands[0]
            return _repair(world, task, planned, executed,
                           {"tool": tool, "args": args}, depth + 1)
        if kind in ("booking", "order"):
            create_tool = "create_booking" if kind == "booking" else "create_order"
            creates = [c for c in planned if c["tool"] == create_tool]
            if creates and _repair(world, task, planned, executed, creates[0], depth + 1):
                new_id = _latest(world, kind)
                if new_id:
                    args[arg] = new_id
                    return _repair(world, task, planned, executed,
                                   {"tool": tool, "args": args}, depth + 1)
            return False
        if kind == "booking_or_order":
            for k in ("booking", "order"):
                nid = _latest(world, k)
                if nid:
                    args[arg] = nid
                    if _repair(world, task, planned, executed,
                               {"tool": tool, "args": args}, depth + 1):
                        return True
            return False
        return False

    if err == "precondition":
        # Redundant confirm (already confirmed) — safely droppable.
        if tool == "confirm_booking" and \
                world.bookings[args["booking_id"]]["status"] == "confirmed":
            return False
        if tool == "pay_booking":
            bk = world.bookings[args["booking_id"]]
            if bk["status"] == "held":
                if _repair(world, task, planned, executed,
                           _call("confirm_booking", booking_id=args["booking_id"]),
                           depth + 1):
                    return _repair(world, task, planned, executed, call, depth + 1)
                return False
            fare = world.flights[bk["flight_id"]]["fare"]
            if args["amount"] != fare:
                args["amount"] = fare
                return _repair(world, task, planned, executed,
                               {"tool": tool, "args": args}, depth + 1)
            return False
        if tool == "pay_order":
            od = world.orders[args["order_id"]]
            if args["amount"] != od["total"]:
                args["amount"] = od["total"]
                return _repair(world, task, planned, executed,
                               {"tool": tool, "args": args}, depth + 1)
            return False
        if tool == "ship_order":
            od = world.orders[args["order_id"]]
            if od["status"] == "created":
                if _repair(world, task, planned, executed,
                           _call("pay_order", order_id=args["order_id"],
                                 amount=od["total"]), depth + 1):
                    return _repair(world, task, planned, executed, call, depth + 1)
                return False
            return False
        if tool == "modify_booking":
            bk = world.bookings[args["booking_id"]]
            if bk["status"] == "held":
                if _repair(world, task, planned, executed,
                           _call("confirm_booking", booking_id=args["booking_id"]),
                           depth + 1):
                    return _repair(world, task, planned, executed, call, depth + 1)
                return False
            _exec(world, executed, _call("search_flights", origin=task["origin"],
                                         dest=task["dest"], date=task["date"]))
            cands = [f for f in _flights(world, task["origin"], task["dest"], task["date"])
                     if f != bk["flight_id"] and world.flights[f]["seats"] > 0]
            if cands:
                args["new_flight_id"] = cands[0]
                return _repair(world, task, planned, executed,
                               {"tool": tool, "args": args}, depth + 1)
            return False
        if tool == "add_item":
            od = world.orders[args["order_id"]]
            query = task.get("query2", task["query"])
            _exec(world, executed, _call("search_products", query=query))
            cands = [p for p in _products(world, query)
                     if world.products[p]["warehouse"] == od["warehouse"]
                     and world.products[p]["stock"] >= args["qty"]]
            if cands:
                args["product_id"] = cands[0]
                return _repair(world, task, planned, executed,
                               {"tool": tool, "args": args}, depth + 1)
            return False
        if tool in ("create_booking", "create_order"):
            if tool == "create_booking":
                _exec(world, executed, _call("search_flights", origin=task["origin"],
                                             dest=task["dest"], date=task["date"]))
                cands = [f for f in _flights(world, task["origin"], task["dest"], task["date"])
                         if world.flights[f]["seats"] > 0]
            else:
                query = task["query"]
                _exec(world, executed, _call("search_products", query=query))
                cands = [p for p in _products(world, query)
                         if world.products[p]["stock"] >= args["qty"]]
            if cands:
                key = "flight_id" if tool == "create_booking" else "product_id"
                args[key] = cands[0]
                return _repair(world, task, planned, executed,
                               {"tool": tool, "args": args}, depth + 1)
            return False
        return False

    return False


def run_checked(task, world, planned, repair):
    """Execute a plan through pre-execution checking.

    repair=False: invalid calls are dropped (check-drop ablation).
    repair=True:  invalid calls go through _repair (Dual-Loop analog).
    Returns the executed trajectory (what the scorer sees).
    """
    w = world.fork()
    executed = []
    for call in planned:
        ok, err = validate(w, call["tool"], call["args"])
        if ok:
            _exec(w, executed, call)
        elif repair:
            _repair(w, task, planned, executed, call, 0)
        # else: dropped
    return executed
